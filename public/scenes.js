let clipCounter = 0;
const MIMI_BODY_PATH = 'M-17 12L-19 7L-17 1L-18 -16Q-18 -32 -8 -35H8Q18 -32 18 -16L17 1L19 7L17 12H12L14 23Q13 28 8 28H3Q0 27 0 23Q0 27 -3 28H-8Q-13 28 -14 23L-12 12Z';

export function mimiSilhouetteMarkup() {
  return `<path d="${MIMI_BODY_PATH}" fill="#fff"/>`;
}

function strokePath(points) {
  if (!points?.length) return '';
  if (points.length === 1) {
    const point = points[0];
    return `M${Number(point.x).toFixed(2)} ${Number(point.y).toFixed(2)}L${Number(point.x).toFixed(2)} ${Number(point.y).toFixed(2)} `;
  }
  return points.map((point, index) => `${index ? 'L' : 'M'}${Number(point.x).toFixed(2)} ${Number(point.y).toFixed(2)} `).join(' ');
}

export function paintStrokesMarkup(strokes = []) {
  let markup = '';
  for (const stroke of strokes) {
    const d = strokePath(stroke.points);
    if (!d) continue;
    const width = TUNING.paintBrushSizes.includes(Number(stroke.width)) ? Number(stroke.width) : TUNING.paintBrushSizes[1];
    if (stroke.erase) {
      const maskId = `mimiPaintErase${++clipCounter}`;
      markup = `<defs><mask id="${maskId}" mask-type="luminance" maskUnits="userSpaceOnUse" x="-40" y="-55" width="80" height="95"><rect x="-40" y="-55" width="80" height="95" fill="white" opacity="1"/><path d="${d}" fill="none" stroke="black" stroke-opacity="1" opacity="1" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round"/></mask></defs><g mask="url(#${maskId})">${markup}</g>`;
      continue;
    }
    const color = /^#[0-9a-f]{6}$/i.test(stroke.color || '') ? stroke.color : '#8b9a90';
    markup += `<path d="${d}" fill="none" stroke="${color}" stroke-width="${width}" stroke-opacity="${TUNING.paintOpacity}" stroke-linecap="round" stroke-linejoin="round"/>`;
  }
  return markup;
}

export function renderMimi({ x = 600, y = 390, size = 1, interactive = false, outlineOpacity = TUNING.outlineOpacity, outlineWidth = TUNING.outlineWidth, reveal = false, layerId = 'targetLayer', paint = [], paintOnly = false } = {}) {
  const handle = interactive ? '<rect data-target-hit="true" x="-29" y="-46" width="58" height="76" fill="transparent" pointer-events="all"/>' : '';
  const id = layerId ? `id="${layerId}"` : '';
  const clipId = `mimiPaintClip${++clipCounter}`;
  const paintedStrokes = paintStrokesMarkup(paint);
  if (paintOnly) {
    return `<g ${id} transform="translate(${x} ${y}) scale(${size})"><defs><clipPath id="${clipId}" clipPathUnits="userSpaceOnUse"><path d="${MIMI_BODY_PATH}"/></clipPath></defs><g clip-path="url(#${clipId})" class="mimi-paint">${paintedStrokes}</g></g>`;
  }
  return `<g ${id} class="scene-target${reveal ? ' reveal-target' : ''}" transform="translate(${x} ${y}) scale(${size})" style="--outline-alpha:${outlineOpacity}">
    <defs><clipPath id="${clipId}" clipPathUnits="userSpaceOnUse"><path d="${MIMI_BODY_PATH}"/></clipPath></defs>
    <g class="mimi-sprite" pointer-events="none" stroke="${TUNING.outlineColor}" stroke-width="${outlineWidth}" stroke-opacity="var(--outline-alpha)" stroke-linejoin="round" stroke-linecap="round">
      <path d="${MIMI_BODY_PATH}" fill="${TUNING.targetColor}"/>
      <path d="M-12 -23Q-12 -28 -7 -28H7Q12 -28 12 -23V-17Q12 -14 8 -14H-8Q-12 -14 -12 -17Z" fill="${TUNING.faceColor}" stroke="${TUNING.targetShade}" stroke-width=".55"/>
      <g clip-path="url(#${clipId})" class="mimi-paint">${paintedStrokes}</g>
    </g>
    ${handle}
  </g>`;
}

export function mimiCardSvg(paint = []) {
  return `<svg width="32" height="38" viewBox="-28 -48 56 82" aria-hidden="true">${renderMimi({ x: 0, y: 0, size: .83, outlineOpacity: .7, layerId: null, paint })}</svg>`;
}
